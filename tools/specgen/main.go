// Command specgen extracts the HTTP API of a SwimResults Go service (Gin + service-core/security)
// using full type information, and either writes a baseline OpenAPI 3.0.3 spec or checks an existing
// spec for drift.
//
//	specgen -service meeting -dir ../server/meeting-service -out specs/meeting.yaml          # write baseline (refuses to overwrite)
//	specgen -service meeting -dir ../server/meeting-service -out specs/meeting.yaml -force   # regenerate
//	specgen -service meeting -dir ../server/meeting-service -check specs/meeting.yaml        # drift check (CI)
//
// What it understands:
//   - routes:   router.<METHOD>(path, h) and security.Route(router, method, path, perm, h...)
//   - auth:     security.Permission* levels, service-core defaults for unregistered routes, ExcludedPaths
//   - inputs:   c.Param, c.Query/DefaultQuery/GetQuery, c.BindJSON/ShouldBind*/BindQuery, c.GetRawData, c.FormFile
//   - outputs:  c.IndentedJSON/JSON (status + Go type), c.String, c.Status, c.Stream/SSEvent
//   - types:    structs (json tags), enums (typed consts), ObjectID, time.Time, pointers, slices, maps
//
// Helper functions in the controller package that receive the *gin.Context are followed.
package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/constant"
	"go/types"
	"os"
	"os/exec"
	"path/filepath"
	"reflect"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"golang.org/x/tools/go/packages"
	"gopkg.in/yaml.v3"
)

func main() {
	svc := flag.String("service", "", "service name, e.g. meeting (used for server URLs and titles)")
	dir := flag.String("dir", "", "path to the service repo checkout")
	out := flag.String("out", "", "write a baseline spec to this file")
	force := flag.Bool("force", false, "overwrite -out if it exists")
	check := flag.String("check", "", "compare routes/permissions in code with this spec; exit 1 on drift")
	flag.Parse()
	if *svc == "" || *dir == "" || (*out == "") == (*check == "") {
		fmt.Fprintln(os.Stderr, "usage: specgen -service <name> -dir <repo> (-out <file> [-force] | -check <file>)")
		os.Exit(2)
	}

	api, err := extract(*dir)
	if err != nil {
		fmt.Fprintln(os.Stderr, "extract:", err)
		os.Exit(1)
	}

	if *check != "" {
		os.Exit(checkDrift(api, *check))
	}
	if _, err := os.Stat(*out); err == nil && !*force {
		fmt.Fprintf(os.Stderr, "%s exists; the committed spec is the source of truth. Use -check, or -force to regenerate.\n", *out)
		os.Exit(1)
	}
	doc := buildSpec(*svc, *dir, api)
	b, err := yamlMarshal(doc)
	if err != nil {
		fmt.Fprintln(os.Stderr, "yaml:", err)
		os.Exit(1)
	}
	header := fmt.Sprintf("# Baseline generated by tools/specgen from SwimResults/%s-service (%s).\n"+
		"# This file is now the source of truth: edit it by hand; CI checks routes/permissions against the code.\n", *svc, gitDescribe(*dir))
	if err := os.WriteFile(*out, append([]byte(header), b...), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("wrote %s: %d operations, %d schemas\n", *out, len(api.routes), len(api.schemas.order))
}

// ---------------------------------------------------------------- model

type param struct {
	Name, In, Format string // Format: "", "objectid", "integer", "boolean", "number"
	Required         bool
	Default          string
}

type response struct {
	Status      string // "200", "default"
	ContentType string // application/json, text/plain, text/event-stream, ""
	Schemas     []any  // one entry per distinct Go type seen for this status
	seen        map[string]bool
}

type route struct {
	Method, GinPath, Path string
	Perm                  string // public | admin | manager | meeting | default | none
	PermSource            string // registered | implicit | excluded
	Handler               string
	Params                map[string]*param
	ParamOrder            []string
	Body                  any // schema
	BodyContentType       string
	Responses             map[string]*response
	RequiresUser          bool // handler reads token claims itself
}

type extracted struct {
	routes   []*route
	schemas  *schemaSet
	excluded []string
	module   string
}

// ---------------------------------------------------------------- extraction

func extract(dir string) (*extracted, error) {
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax | packages.NeedTypes |
			packages.NeedTypesInfo | packages.NeedImports | packages.NeedDeps | packages.NeedModule,
		Dir: dir,
	}
	pkgs, err := packages.Load(cfg, "./controller")
	if err != nil {
		return nil, err
	}
	if packages.PrintErrors(pkgs) > 0 || len(pkgs) != 1 {
		return nil, fmt.Errorf("could not load %s/controller cleanly", dir)
	}
	p := pkgs[0]
	ex := &extracted{module: p.Module.Path}
	ex.schemas = newSchemaSet(ex.module)

	decls := map[*types.Func]*ast.FuncDecl{}
	for _, f := range p.Syntax {
		for _, d := range f.Decls {
			if fd, ok := d.(*ast.FuncDecl); ok {
				if obj, ok := p.TypesInfo.Defs[fd.Name].(*types.Func); ok {
					decls[obj] = fd
				}
			}
		}
	}

	a := &analyzer{info: p.TypesInfo, decls: decls, schemas: ex.schemas}

	// 1. ExcludedPaths from security.InitAuthMiddleware(&security.AuthMiddlewareConfig{ExcludedPaths: [...]})
	for _, f := range p.Syntax {
		ast.Inspect(f, func(n ast.Node) bool {
			kv, ok := n.(*ast.KeyValueExpr)
			if !ok {
				return true
			}
			if id, ok := kv.Key.(*ast.Ident); ok && id.Name == "ExcludedPaths" {
				if cl, ok := kv.Value.(*ast.CompositeLit); ok {
					for _, e := range cl.Elts {
						if s, ok := a.constString(e); ok {
							ex.excluded = append(ex.excluded, s)
						}
					}
				}
			}
			return true
		})
	}

	// 2. route registrations
	for _, f := range p.Syntax {
		ast.Inspect(f, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok {
				return true
			}
			sel, ok := call.Fun.(*ast.SelectorExpr)
			if !ok {
				return true
			}
			var methods []string
			var pathExpr ast.Expr
			var handlerExpr ast.Expr
			perm, permSrc := "", "implicit"

			switch {
			case isPkgFunc(a.info, sel, "github.com/swimresults/service-core/security", "Route") && len(call.Args) >= 5:
				m, ok1 := a.constString(call.Args[1])
				if !ok1 {
					return true
				}
				methods = []string{strings.ToUpper(m)}
				pathExpr = call.Args[2]
				perm = strings.ToLower(strings.TrimPrefix(lastSelName(call.Args[3]), "Permission"))
				permSrc = "registered"
				handlerExpr = call.Args[len(call.Args)-1]
			case isGinEngine(a.info, sel.X) && len(call.Args) >= 2:
				switch sel.Sel.Name {
				case "GET", "POST", "PUT", "PATCH", "DELETE", "HEAD":
					methods = []string{sel.Sel.Name}
				case "Any":
					methods = []string{"GET", "POST", "PUT", "PATCH", "DELETE"}
				default:
					return true // OPTIONS (CORS only), Use, ...
				}
				pathExpr = call.Args[0]
				handlerExpr = call.Args[len(call.Args)-1]
			default:
				return true
			}
			ginPath, ok := a.constString(pathExpr)
			if !ok {
				fmt.Fprintf(os.Stderr, "warning: non-constant route path at %s\n", a.pos(call))
				return true
			}
			for _, m := range methods {
				r := &route{Method: m, GinPath: ginPath, Path: toOpenAPIPath(ginPath), Perm: perm, PermSource: permSrc,
					Params: map[string]*param{}, Responses: map[string]*response{}}
				if r.Perm == "" {
					r.Perm = implicitPerm(m)
				}
				for _, ep := range ex.excluded {
					if strings.HasPrefix(ginPath, ep) {
						r.Perm, r.PermSource = "none", "excluded"
					}
				}
				for _, seg := range strings.Split(ginPath, "/") {
					if strings.HasPrefix(seg, ":") || strings.HasPrefix(seg, "*") {
						r.addParam(seg[1:], "path").Required = true
					}
				}
				if fn := a.funcOf(handlerExpr); fn != nil {
					r.Handler = fn.Name()
					a.analyze(r, fn, 0, map[*types.Func]bool{})
				}
				ex.routes = append(ex.routes, r)
			}
			return true
		})
	}

	// actuator is registered after the middleware and excluded explicitly; nothing special needed.
	sort.SliceStable(ex.routes, func(i, j int) bool {
		if ex.routes[i].Path != ex.routes[j].Path {
			return ex.routes[i].Path < ex.routes[j].Path
		}
		return methodOrder(ex.routes[i].Method) < methodOrder(ex.routes[j].Method)
	})
	return ex, nil
}

// service-core default for routes without a registered permission.
func implicitPerm(method string) string {
	if method == "GET" || method == "HEAD" {
		return "public"
	}
	return "default" // meeting permission if a meeting id is present, otherwise admin
}

func (r *route) addParam(name, in string) *param {
	key := in + ":" + name
	if p, ok := r.Params[key]; ok {
		return p
	}
	p := &param{Name: name, In: in}
	r.Params[key] = p
	r.ParamOrder = append(r.ParamOrder, key)
	return p
}

type analyzer struct {
	info    *types.Info
	decls   map[*types.Func]*ast.FuncDecl
	schemas *schemaSet
}

func (a *analyzer) pos(n ast.Node) string { return fmt.Sprint(n.Pos()) }

func (a *analyzer) constString(e ast.Expr) (string, bool) {
	tv, ok := a.info.Types[e]
	if !ok || tv.Value == nil || tv.Value.Kind() != constant.String {
		return "", false
	}
	return constant.StringVal(tv.Value), true
}

func (a *analyzer) funcOf(e ast.Expr) *types.Func {
	switch x := e.(type) {
	case *ast.Ident:
		f, _ := a.info.Uses[x].(*types.Func)
		return f
	case *ast.SelectorExpr:
		f, _ := a.info.Uses[x.Sel].(*types.Func)
		return f
	}
	return nil
}

// analyze walks a handler (or helper) that has a *gin.Context parameter.
func (a *analyzer) analyze(r *route, fn *types.Func, depth int, visiting map[*types.Func]bool) {
	decl := a.decls[fn]
	if decl == nil || decl.Body == nil || depth > 4 || visiting[fn] {
		return
	}
	visiting[fn] = true
	defer delete(visiting, fn)

	ctxVars := map[types.Object]bool{}
	sig := fn.Type().(*types.Signature)
	for i := 0; i < sig.Params().Len(); i++ {
		if isGinContext(sig.Params().At(i).Type()) {
			ctxVars[sig.Params().At(i)] = true
		}
	}
	if len(ctxVars) == 0 {
		return
	}
	isCtx := func(e ast.Expr) bool {
		id, ok := e.(*ast.Ident)
		return ok && ctxVars[a.info.Uses[id]]
	}
	ctxCall := func(e ast.Expr) (string, *ast.CallExpr) {
		call, ok := e.(*ast.CallExpr)
		if !ok {
			return "", nil
		}
		sel, ok := call.Fun.(*ast.SelectorExpr)
		if !ok || !isCtx(sel.X) {
			return "", nil
		}
		return sel.Sel.Name, call
	}

	ast.Inspect(decl.Body, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		// format hints: ObjectIDFromHex(c.Param("x")), strconv.Atoi(c.Query("x")), ...
		if callee := a.funcOf(call.Fun); callee != nil && len(call.Args) > 0 {
			format := ""
			switch callee.Name() {
			case "ObjectIDFromHex":
				format = "objectid"
			case "Atoi", "ParseInt", "ParseUint":
				format = "integer"
			case "ParseBool":
				format = "boolean"
			case "ParseFloat":
				format = "number"
			}
			if format != "" {
				if name, inner := ctxCall(call.Args[0]); inner != nil && len(inner.Args) > 0 {
					if pn, ok := a.constString(inner.Args[0]); ok {
						switch name {
						case "Param":
							r.addParam(pn, "path").Format = format
						case "Query", "DefaultQuery", "GetQuery":
							r.addParam(pn, "query").Format = format
						}
					}
				}
			}
			if regexp.MustCompile(`(?i)claims|getuserid`).MatchString(callee.Name()) {
				r.RequiresUser = true
			}
			// io.ReadAll(c.Request.Body): raw body passed through as-is -> free-form JSON
			if callee.Name() == "ReadAll" && callee.Pkg() != nil && (callee.Pkg().Path() == "io" || callee.Pkg().Path() == "io/ioutil") {
				if body, ok := call.Args[0].(*ast.SelectorExpr); ok && body.Sel.Name == "Body" {
					if req, ok := body.X.(*ast.SelectorExpr); ok && req.Sel.Name == "Request" && isCtx(req.X) && r.Body == nil {
						if assignsRawQuery(decl.Body) {
							// body copied into c.Request.URL.RawQuery and bound as query: form-encoded (EasyWK)
							r.Body = om("type", "object", "additionalProperties", om("type", "string"),
								"description", "form-encoded fields, parsed like query parameters")
							r.BodyContentType = "application/x-www-form-urlencoded"
						} else {
							r.Body = om("description", "free-form JSON, passed through unchanged")
							r.BodyContentType = "application/json"
						}
					}
				}
			}
		}

		name, cc := ctxCall(call)
		if cc == nil {
			// follow helpers that receive the context
			if callee := a.funcOf(call.Fun); callee != nil {
				for _, arg := range call.Args {
					if isCtx(arg) {
						a.analyze(r, callee, depth+1, visiting)
						break
					}
				}
			}
			return true
		}
		switch name {
		case "Param":
			if pn, ok := a.constString(cc.Args[0]); ok {
				r.addParam(pn, "path").Required = true
			}
		case "Query", "GetQuery":
			if pn, ok := a.constString(cc.Args[0]); ok {
				r.addParam(pn, "query")
			}
		case "DefaultQuery":
			if pn, ok := a.constString(cc.Args[0]); ok {
				p := r.addParam(pn, "query")
				if d, ok := a.constString(cc.Args[1]); ok {
					p.Default = d
				}
			}
		case "BindJSON", "ShouldBindJSON", "ShouldBind", "Bind":
			if t := a.pointee(cc.Args[0]); t != nil {
				r.Body = a.schemas.of(t)
				r.BodyContentType = "application/json"
			}
		case "BindQuery", "ShouldBindQuery":
			if t := a.pointee(cc.Args[0]); t != nil {
				if st, ok := t.Underlying().(*types.Struct); ok {
					for i := 0; i < st.NumFields(); i++ {
						f := st.Field(i)
						qn := reflect.StructTag(st.Tag(i)).Get("form")
						if qn == "" || qn == "-" {
							qn = f.Name()
						}
						p := r.addParam(strings.Split(qn, ",")[0], "query")
						if s := basicFormat(f.Type()); s != "" {
							p.Format = s
						}
					}
				}
			}
		case "GetRawData":
			r.Body = map[string]any{"type": "string"}
			r.BodyContentType = "text/plain"
		case "FormFile":
			if fn, ok := a.constString(cc.Args[0]); ok {
				r.Body = om("type", "object", "properties", om(fn, om("type", "string", "format", "binary")))
				r.BodyContentType = "multipart/form-data"
			}
		case "IndentedJSON", "JSON", "PureJSON", "SecureJSON", "AbortWithStatusJSON":
			if len(cc.Args) == 2 {
				status := a.status(cc.Args[0])
				t := a.info.TypeOf(cc.Args[1])
				var s any
				if isGinH(t) {
					if st, _ := strconv.Atoi(status); st >= 400 {
						s = a.schemas.ref("Error")
					} else {
						s = om("type", "object", "additionalProperties", true)
					}
				} else {
					s = a.schemas.of(t)
					// Go encodes nil slices/maps as JSON null (e.g. an empty list): the response is nullable
					switch types.Unalias(t).Underlying().(type) {
					case *types.Slice, *types.Map:
						s = a.schemas.nullable(s)
					}
				}
				r.addResponse(status, "application/json", s, types.TypeString(t, nil))
			}
		case "String":
			if len(cc.Args) >= 1 {
				r.addResponse(a.status(cc.Args[0]), "text/plain", om("type", "string"), "string")
			}
		case "Status", "AbortWithStatus":
			if len(cc.Args) == 1 {
				r.addResponse(a.status(cc.Args[0]), "", nil, "")
			}
		case "Stream", "SSEvent":
			r.addResponse("200", "text/event-stream", om("type", "string"), "sse")
		}
		return true
	})
}

func (r *route) addResponse(status, ct string, schema any, key string) {
	resp, ok := r.Responses[status]
	if !ok {
		resp = &response{Status: status, ContentType: ct, seen: map[string]bool{}}
		r.Responses[status] = resp
	}
	if resp.ContentType == "" {
		resp.ContentType = ct
	}
	if schema != nil && !resp.seen[key] {
		resp.seen[key] = true
		resp.Schemas = append(resp.Schemas, schema)
	}
}

func (a *analyzer) status(e ast.Expr) string {
	if tv, ok := a.info.Types[e]; ok && tv.Value != nil {
		if v, ok := constant.Int64Val(tv.Value); ok {
			return strconv.FormatInt(v, 10)
		}
	}
	return "default"
}

func (a *analyzer) pointee(e ast.Expr) types.Type {
	t := a.info.TypeOf(e)
	if t == nil {
		return nil
	}
	if p, ok := t.(*types.Pointer); ok {
		return p.Elem()
	}
	return t
}

// ---------------------------------------------------------------- type helpers

func isPkgFunc(info *types.Info, sel *ast.SelectorExpr, pkg, name string) bool {
	f, ok := info.Uses[sel.Sel].(*types.Func)
	return ok && f.Pkg() != nil && f.Pkg().Path() == pkg && f.Name() == name
}

func isNamed(t types.Type, pkg, name string) bool {
	if p, ok := t.(*types.Pointer); ok {
		t = p.Elem()
	}
	n, ok := t.(*types.Named)
	return ok && n.Obj().Pkg() != nil && n.Obj().Pkg().Path() == pkg && n.Obj().Name() == name
}

func isGinEngine(info *types.Info, e ast.Expr) bool {
	t := info.TypeOf(e)
	return t != nil && (isNamed(t, "github.com/gin-gonic/gin", "Engine") || isNamed(t, "github.com/gin-gonic/gin", "RouterGroup"))
}

func isGinContext(t types.Type) bool { return isNamed(t, "github.com/gin-gonic/gin", "Context") }
func isGinH(t types.Type) bool       { return t != nil && isNamed(t, "github.com/gin-gonic/gin", "H") }

func lastSelName(e ast.Expr) string {
	if s, ok := e.(*ast.SelectorExpr); ok {
		return s.Sel.Name
	}
	if id, ok := e.(*ast.Ident); ok {
		return id.Name
	}
	return ""
}

func basicFormat(t types.Type) string {
	b, ok := t.Underlying().(*types.Basic)
	if !ok {
		return ""
	}
	switch {
	case b.Info()&types.IsInteger != 0:
		return "integer"
	case b.Info()&types.IsFloat != 0:
		return "number"
	case b.Info()&types.IsBoolean != 0:
		return "boolean"
	}
	return ""
}

var ginParam = regexp.MustCompile(`[:*]([A-Za-z0-9_]+)`)

func toOpenAPIPath(p string) string { return ginParam.ReplaceAllString(p, "{$1}") }

func methodOrder(m string) int {
	return strings.Index("GET HEAD POST PUT PATCH DELETE", m)
}

// ---------------------------------------------------------------- schemas

type schemaSet struct {
	module string
	defs   map[string]any
	order  []string
	names  map[*types.TypeName]string
}

func newSchemaSet(module string) *schemaSet {
	s := &schemaSet{module: module, defs: map[string]any{}, names: map[*types.TypeName]string{}}
	s.add("Error", om("type", "object", "properties", om("message", om("type", "string")), "required", []string{"message"}))
	s.add("ObjectId", om("type", "string", "pattern", "^[0-9a-fA-F]{24}$", "description", "MongoDB ObjectID (hex)"))
	return s
}

func (s *schemaSet) add(name string, def any) {
	if _, ok := s.defs[name]; !ok {
		s.order = append(s.order, name)
	}
	s.defs[name] = def
}

func (s *schemaSet) ref(name string) any { return om("$ref", "#/components/schemas/"+name) }

// nullable marks a schema as nullable, OpenAPI 3.0 style (3.0.3 has the widest generator support).
// 3.0.3 requires `type` next to `nullable`, so for $refs the referenced component's type is repeated.
func (s *schemaSet) nullable(schema any) any {
	m, ok := schema.(*orderedMap)
	if !ok {
		return schema
	}
	if _, isRef := m.vals["$ref"]; isRef {
		if inline := s.inlineScalar(m); inline != nil {
			inline.set("nullable", true)
			return inline
		}
		// object $ref: left as plain $ref; the caller makes the field optional instead of nullable
		return m
	}
	c := om()
	for _, k := range m.keys {
		c.set(k, m.vals[k])
	}
	c.set("nullable", true)
	return c
}

func (s *schemaSet) of(t types.Type) any {
	switch tt := t.(type) {
	case *types.Pointer:
		return s.of(tt.Elem())
	case *types.Alias:
		return s.of(types.Unalias(tt))
	case *types.Named:
		obj := tt.Obj()
		path := ""
		if obj.Pkg() != nil {
			path = obj.Pkg().Path()
		}
		switch {
		case path == "go.mongodb.org/mongo-driver/bson/primitive" && obj.Name() == "ObjectID":
			return s.ref("ObjectId")
		case path == "go.mongodb.org/mongo-driver/bson/primitive" && obj.Name() == "DateTime",
			path == "time" && obj.Name() == "Time":
			return om("type", "string", "format", "date-time")
		case path == "time" && obj.Name() == "Duration":
			return om("type", "integer", "format", "int64", "description", "duration in nanoseconds",
				"x-go-type", "time.Duration") // generated Go code already imports "time" for date-time fields
		case path == "encoding/json" && obj.Name() == "RawMessage":
			return om()
		case path == "github.com/gin-gonic/gin" && obj.Name() == "H":
			return om("type", "object", "additionalProperties", true)
		}
		if name, ok := s.names[obj]; ok {
			return s.ref(name)
		}
		switch u := tt.Underlying().(type) {
		case *types.Struct:
			name := s.uniqueName(obj)
			s.names[obj] = name
			s.add(name, nil) // reserve (recursion)
			s.add(name, s.structSchema(u, obj))
			return s.ref(name)
		case *types.Basic:
			if enum := enumValues(tt); len(enum) > 0 {
				name := s.uniqueName(obj)
				s.names[obj] = name
				base := s.of(u).(*orderedMap)
				base.set("enum", enum)
				s.add(name, base)
				return s.ref(name)
			}
			return s.of(u)
		default:
			return s.of(u)
		}
	case *types.Basic:
		switch {
		case tt.Kind() == types.String:
			return om("type", "string")
		case tt.Info()&types.IsBoolean != 0:
			return om("type", "boolean")
		case tt.Info()&types.IsInteger != 0:
			// plain Go int/uint: no format, so generators use their native int (Go: int)
			switch tt.Kind() {
			case types.Int64, types.Uint64:
				return om("type", "integer", "format", "int64")
			case types.Int32, types.Uint32, types.Int16, types.Uint16, types.Int8, types.Uint8:
				return om("type", "integer", "format", "int32")
			}
			return om("type", "integer")
		case tt.Info()&types.IsFloat != 0:
			return om("type", "number", "format", "double")
		}
		return om()
	case *types.Slice:
		if b, ok := tt.Elem().(*types.Basic); ok && b.Kind() == types.Byte {
			return om("type", "string", "format", "byte")
		}
		return om("type", "array", "items", s.of(tt.Elem()))
	case *types.Array:
		return om("type", "array", "items", s.of(tt.Elem()))
	case *types.Map:
		return om("type", "object", "additionalProperties", s.of(tt.Elem()))
	case *types.Interface:
		return om()
	case *types.Struct:
		return s.structSchema(tt, nil)
	}
	return om()
}

func (s *schemaSet) uniqueName(obj *types.TypeName) string {
	name := obj.Name()
	for _, other := range s.order {
		if other == name {
			// collision: prefix with package name, e.g. DtoImportEvent
			pkg := obj.Pkg().Name()
			name = strings.ToUpper(pkg[:1]) + pkg[1:] + name
			if strings.HasPrefix(obj.Pkg().Path(), "github.com/swimresults/") && !strings.HasPrefix(obj.Pkg().Path(), s.module) {
				// type from another SwimResults service
				svc := strings.TrimSuffix(strings.Split(strings.TrimPrefix(obj.Pkg().Path(), "github.com/swimresults/"), "/")[0], "-service")
				name = strings.ToUpper(svc[:1]) + svc[1:] + obj.Name()
			}
			break
		}
	}
	return name
}

func (s *schemaSet) structSchema(st *types.Struct, owner *types.TypeName) any {
	props := om()
	var required []string
	var allOf []any
	for i := 0; i < st.NumFields(); i++ {
		f := st.Field(i)
		tag := reflect.StructTag(st.Tag(i)).Get("json")
		if tag == "-" || (!f.Exported() && !f.Embedded()) {
			continue
		}
		parts := strings.Split(tag, ",")
		name := parts[0]
		omitempty := false
		for _, o := range parts[1:] {
			if o == "omitempty" || o == "omitzero" {
				omitempty = true
			}
		}
		if f.Embedded() && name == "" {
			allOf = append(allOf, s.of(f.Type()))
			continue
		}
		if name == "" {
			name = f.Name()
		}
		fs := s.of(f.Type())
		switch u := types.Unalias(f.Type()).(type) {
		case *types.Pointer:
			fs = s.nullable(fs)
		case *types.Slice, *types.Map:
			if _, isNamed := f.Type().(*types.Named); !isNamed || !isByteSlice(u) {
				fs = s.nullable(fs)
			}
		}
		// keep the Go field name for the generated Go client when it differs from the default (e.g. _id -> Identifier)
		if f.Name() != defaultGoName(name) {
			if m, ok := fs.(*orderedMap); ok {
				if _, isRef := m.vals["$ref"]; isRef {
					// OpenAPI 3.0 ignores siblings of $ref, and wrapping in allOf produces wrapper types in the
					// Swift/Kotlin clients: inline scalar components (e.g. ObjectId); object refs keep the default Go name
					if inline := s.inlineScalar(m); inline != nil {
						inline.set("x-go-name", f.Name())
						fs = inline
					}
				} else {
					m.set("x-go-name", f.Name())
				}
			}
		}
		if _, isPtr := types.Unalias(f.Type()).(*types.Pointer); isPtr {
			if m, ok := fs.(*orderedMap); ok {
				if _, isRef := m.vals["$ref"]; isRef {
					omitempty = true // nil pointer -> null; modelled as an optional field
				}
			}
		}
		props.set(name, fs)
		// encoding/json ignores omitempty for structs and arrays (e.g. time.Time, ObjectID): always emitted
		switch types.Unalias(f.Type()).Underlying().(type) {
		case *types.Struct, *types.Array:
			omitempty = false
		}
		if !omitempty {
			required = append(required, name)
		}
	}
	obj := om("type", "object", "properties", props)
	if len(required) > 0 {
		obj.set("required", required)
	}
	if len(allOf) > 0 {
		return om("allOf", append(allOf, obj))
	}
	return obj
}

func isByteSlice(t types.Type) bool {
	sl, ok := t.(*types.Slice)
	if !ok {
		return false
	}
	b, ok := sl.Elem().(*types.Basic)
	return ok && b.Kind() == types.Byte
}

func enumValues(n *types.Named) []any {
	pkg := n.Obj().Pkg()
	if pkg == nil {
		return nil
	}
	var vals []any
	scope := pkg.Scope()
	for _, name := range scope.Names() {
		c, ok := scope.Lookup(name).(*types.Const)
		if !ok || !types.Identical(c.Type(), n) {
			continue
		}
		switch c.Val().Kind() {
		case constant.String:
			vals = append(vals, constant.StringVal(c.Val()))
		case constant.Int:
			v, _ := constant.Int64Val(c.Val())
			vals = append(vals, v)
		}
	}
	sort.Slice(vals, func(i, j int) bool { return fmt.Sprint(vals[i]) < fmt.Sprint(vals[j]) })
	return vals
}

