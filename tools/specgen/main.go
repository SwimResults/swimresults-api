var permDescriptions = map[string]string{
	"public":  "Public — no authentication required.",
	"none":    "Excluded from the auth middleware entirely.",
	"admin":   "Requires Keycloak realm role `admin` (or the service key).",
	"manager": "Requires realm role `manager` or `admin` (any meeting), or the service key.",
	"meeting": "Requires `admin`, or `manager` with the meeting id in the token's `events` claim; or the service key. The meeting id is read from `meet_id`/`meetid`/`meeting` in path, query or JSON body.",
	"default": "Not registered with a permission: service-core applies the meeting rule if a meeting id is present, otherwise requires `admin`.",
}

func buildSpec(svc, dir string, ex *extracted) any {
	paths := om()
	usedIDs := map[string]int{}
	for _, r := range ex.routes {
		item, _ := paths.get(r.Path).(*orderedMap)
		if item == nil {
			item = om()
			paths.set(r.Path, item)
		}
		op := om()
		tag := strings.Split(strings.Trim(r.GinPath, "/"), "/")[0]
		op.set("tags", []string{tag})
		id := r.Handler
		if id == "" {
			id = strings.ToLower(r.Method) + strings.ReplaceAll(r.Path, "/", "_")
		}
		if n := usedIDs[id]; n > 0 {
			usedIDs[id]++
			id = fmt.Sprintf("%s%s", id, strings.Title(strings.ToLower(r.Method)))
		} else {
			usedIDs[id] = 1
		}
		op.set("operationId", id)
		op.set("x-permission", r.Perm)
		if r.PermSource != "registered" {
			op.set("x-permission-source", r.PermSource)
		}
		desc := permDescriptions[r.Perm]
		if r.RequiresUser {
			desc += " The handler reads the user from the bearer token, so a token is required in practice."
		}
		op.set("description", desc)

		var params []any
		for _, k := range r.ParamOrder {
			p := r.Params[k]
			schema := om("type", "string")
			switch p.Format {
			case "objectid":
				schema = om("$ref", "#/components/schemas/ObjectId")
			case "integer":
				schema = om("type", "integer")
			case "boolean":
				schema = om("type", "boolean")
			case "number":
				schema = om("type", "number")
			}
			if p.Default != "" {
				schema.set("default", p.Default)
			}
			pm := om("name", p.Name, "in", p.In)
			if p.In == "path" || p.Required {
				pm.set("required", true)
			}
			pm.set("schema", schema)
			if p.In == "query" && !p.Required {
				// keep optional query params as pointers in Go, so unset params are not sent (?limit=0&query=)
				pm.set("x-go-type-skip-optional-pointer", false)
			}
			params = append(params, pm)
		}
		if len(params) > 0 {
			op.set("parameters", params)
		}
		if r.Body != nil && r.Method != "GET" && r.Method != "HEAD" {
			op.set("requestBody", om("required", true, "content", om(r.BodyContentType, om("schema", r.Body))))
		}

		switch {
		case r.Perm == "public" && r.RequiresUser:
			op.set("security", []any{om("bearerAuth", []any{})})
		case r.Perm == "public" || r.Perm == "none":
			op.set("security", []any{})
		default:
			op.set("security", []any{om("bearerAuth", []any{}), om("serviceKey", []any{})})
		}

		resps := om()
		var codes []string
		for c := range r.Responses {
			codes = append(codes, c)
		}
		sort.Strings(codes)
		for _, c := range codes {
			resp := r.Responses[c]
			rm := om("description", statusText(c))
			if len(resp.Schemas) > 0 && resp.ContentType != "" {
				var schema any = resp.Schemas[0]
				if len(resp.Schemas) > 1 {
					schema = om("oneOf", resp.Schemas)
				}
				rm.set("content", om(resp.ContentType, om("schema", schema)))
			}
			resps.set(c, rm)
		}
		if len(codes) == 0 {
			resps.set("default", om("description", "not determined by specgen"))
		}
		op.set("responses", resps)
		item.set(strings.ToLower(r.Method), op)
	}

	schemas := om()
	for _, n := range ex.schemas.order {
		schemas.set(n, ex.schemas.defs[n])
	}
	title := strings.ToUpper(svc[:1]) + svc[1:] + " Service API"
	return om(
		"openapi", "3.0.3",
		"info", om("title", title, "version", strings.TrimPrefix(gitDescribe(dir), "v"),
			"description", fmt.Sprintf("SwimResults %s-service. Routes are served at the service root; the public gateway adds the `/%s/v1` prefix.", svc, svc)),
		"servers", []any{
			om("url", fmt.Sprintf("https://api.swimresults.de/%s/v1", svc), "description", "production"),
			om("url", fmt.Sprintf("https://api-dev.swimresults.de/%s/v1", svc), "description", "development"),
			om("url", fmt.Sprintf("http://localhost:8090/%s/v1", svc), "description", "local (dev/docker-compose.yml gateway)"),
		},
		"paths", paths,
		"components", om(
			"securitySchemes", om(
				"bearerAuth", om("type", "http", "scheme", "bearer", "bearerFormat", "JWT",
					"description", "Keycloak access token (realm swimresults, RS256)."),
				"serviceKey", om("type", "apiKey", "in", "header", "name", "X-Swimresults-Service",
					"description", "Shared service-to-service key; bypasses permission checks. Internal use only."),
			),
			"schemas", schemas,
		),
	)
}

func statusText(code string) string {
	if c, err := strconv.Atoi(code); err == nil {
		if t := httpStatusText(c); t != "" {
			return t
		}
	}
	return "response"
}

func httpStatusText(c int) string {
	m := map[int]string{200: "OK", 201: "Created", 202: "Accepted", 204: "No Content", 400: "Bad Request",
		401: "Unauthorized", 403: "Forbidden", 404: "Not Found", 409: "Conflict", 422: "Unprocessable Entity",
		500: "Internal Server Error", 501: "Not Implemented", 503: "Service Unavailable"}
	return m[c]
}

func gitDescribe(dir string) string {
	out, err := exec.Command("git", "-C", dir, "describe", "--tags", "--always").Output()
	if err != nil {
		return "0.0.0"
	}
	return strings.TrimSpace(string(out))
}

// ---------------------------------------------------------------- drift check

func checkDrift(ex *extracted, specFile string) int {
	b, err := os.ReadFile(specFile)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	var spec struct {
		Paths map[string]map[string]map[string]any `yaml:"paths"`
	}
	if err := yaml.Unmarshal(b, &spec); err != nil {
		fmt.Fprintln(os.Stderr, "parse spec:", err)
		return 1
	}
	inSpec := map[string]string{}
	for p, ops := range spec.Paths {
		for m, op := range ops {
			if m == "parameters" || m == "summary" || m == "description" {
				continue
			}
			perm, _ := op["x-permission"].(string)
			inSpec[strings.ToUpper(m)+" "+p] = perm
		}
	}
	inCode := map[string]string{}
	for _, r := range ex.routes {
		inCode[r.Method+" "+r.Path] = r.Perm
	}
	var problems []string
	for k, perm := range inCode {
		sp, ok := inSpec[k]
		switch {
		case !ok:
			problems = append(problems, "missing in spec:   "+k+"  (x-permission: "+perm+")")
		case sp != perm:
			problems = append(problems, fmt.Sprintf("permission differs: %s  code=%s spec=%s", k, perm, sp))
		}
	}
	for k := range inSpec {
		if _, ok := inCode[k]; !ok {
			problems = append(problems, "not in code:       "+k)
		}
	}
	sort.Strings(problems)
	rel := specFile
	if r, err := filepath.Rel(".", specFile); err == nil && !strings.HasPrefix(r, "../../..") {
		rel = r
	}
	if len(problems) == 0 {
		fmt.Printf("%s: %d operations match the code\n", rel, len(inCode))
		return 0
	}
	fmt.Printf("%s: %d drift problem(s)\n", rel, len(problems))
	for _, p := range problems {
		fmt.Println("  " + p)
	}
	return 1
}

// ---------------------------------------------------------------- ordered YAML

type orderedMap struct {
	keys []string
	vals map[string]any
}

func om(kv ...any) *orderedMap {
	m := &orderedMap{vals: map[string]any{}}
	for i := 0; i+1 < len(kv); i += 2 {
		m.set(kv[i].(string), kv[i+1])
	}
	return m
}

func (m *orderedMap) set(k string, v any) {
	if _, ok := m.vals[k]; !ok {
		m.keys = append(m.keys, k)
	}
	m.vals[k] = v
}

func (m *orderedMap) get(k string) any { return m.vals[k] }

func (m *orderedMap) MarshalYAML() (any, error) {
	n := &yaml.Node{Kind: yaml.MappingNode}
	for _, k := range m.keys {
		var v yaml.Node
		if err := v.Encode(m.vals[k]); err != nil {
			return nil, err
		}
		n.Content = append(n.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: k, Tag: "!!str"}, &v)
	}
	return n, nil
}

func yamlMarshal(v any) ([]byte, error) {
	var sb strings.Builder
	enc := yaml.NewEncoder(&sb)
	enc.SetIndent(2)
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return []byte(sb.String()), enc.Close()
}

// defaultGoName approximates oapi-codegen's field naming for a JSON property name (snake_case -> CamelCase).
func defaultGoName(json string) string {
	var b strings.Builder
	for _, part := range regexp.MustCompile(`[^A-Za-z0-9]+`).Split(json, -1) {
		if part != "" {
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	if strings.HasPrefix(json, "_") {
		return "Underscore" + b.String()
	}
	return b.String()
}

// assignsRawQuery reports whether a handler body assigns ...Request.URL.RawQuery.
func assignsRawQuery(body *ast.BlockStmt) bool {
	found := false
	ast.Inspect(body, func(n ast.Node) bool {
		if as, ok := n.(*ast.AssignStmt); ok {
			for _, l := range as.Lhs {
				if sel, ok := l.(*ast.SelectorExpr); ok && sel.Sel.Name == "RawQuery" {
					found = true
				}
			}
		}
		return !found
	})
	return found
}

// inlineScalar returns a copy of a referenced scalar component (e.g. ObjectId: string + pattern), or nil for objects.
func (s *schemaSet) inlineScalar(ref *orderedMap) *orderedMap {
	r, _ := ref.vals["$ref"].(string)
	def, ok := s.defs[strings.TrimPrefix(r, "#/components/schemas/")].(*orderedMap)
	if !ok {
		return nil
	}
	if typ, _ := def.vals["type"].(string); typ == "" || typ == "object" || def.vals["properties"] != nil {
		return nil
	}
	c := om()
	for _, k := range def.keys {
		c.set(k, def.vals[k])
	}
	return c
}
